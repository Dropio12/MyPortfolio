// Writes api/_facts.ts from src/content.ts, so the AI function answers from exactly the facts the
// page shows. Run after any content edit: `npm run facts` (Node 22.18+ reads the .ts file directly).
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const c = await import(pathToFileURL(join(root, 'src', 'content.ts')).href)
const { deep } = await import(pathToFileURL(join(root, 'src', 'deep.ts')).href)

const lines = []
const p = c.person
lines.push(`Name: ${p.name} (short: ${p.shortName}).`)
lines.push(`Role: ${p.role} Targets: ${p.targets}.`)
lines.push(`Availability: ${p.availability.join('. ')}.`)
lines.push(`Contact: email ${p.email}; GitHub ${c.links.github}; LinkedIn ${c.links.linkedin}; resume PDF on the site.`)
lines.push('')
lines.push('Education:')
c.education.forEach(d => lines.push(`- ${d.degree}, ${d.school}, ${d.when}${d.detail ? `. ${d.detail}` : ''}.`))
lines.push(`- ${c.teaching}`)
lines.push(`- ${c.research}`)
lines.push('')
lines.push('Recognition:')
c.recognition.forEach(r => lines.push(`- ${r.figure} ${r.label}${r.detail ? `: ${r.detail}` : ''}.`))
lines.push(`- ${c.hackathonNote}`)
lines.push('')
lines.push(`Client work: ${c.clientWork.line} (${c.clientWork.meta}).`)
lines.push('')
lines.push('Work on the page, each with its id in square brackets:')
c.items.forEach(i => {
	const head = i.position ? `${i.title}, ${i.position}, ${i.dates}` : `${i.title} (${i.meta})`
	const facts = i.facts.map(f => `${f.figure} ${f.text}`).join(' ')
	const notes = (i.notes || []).join(' ')
	const links = i.links.map(l => l.href).join(', ')
	lines.push(
		`- [${i.id}] ${head}. ${i.line} ${facts} ${notes} Stack: ${i.stack.join(', ')}.${links ? ` Links: ${links}.` : ''}`.replace(/\s+/g, ' ')
	)
})

// the long form of each piece of work (src/deep.ts), served by the MCP server's get_work only, so
// the prompt behind /api/ask stays short
const details = {}
for (const i of c.items) {
	const d = deep[i.id]
	if (!d) continue
	const parts = [d.overview.join(' ')]
	if (d.languages?.length) parts.push(`Languages: ${d.languages.map(l => (l.share ? `${l.name} (${l.share}%)` : l.name)).join(', ')}.`)
	for (const g of d.stack) parts.push(`${g.group}: ${g.items.join(', ')}.`)
	const inside = (d.c4?.containers?.nodes || []).filter(n => n.kind === 'container' || n.kind === 'database')
	if (inside.length) parts.push(`Parts: ${inside.map(n => `${n.label}${n.tech ? ` (${n.tech})` : ''}: ${n.desc || ''}`).join('; ')}.`)
	details[i.id] = parts.join('\n')
}

const out = {
	knowledge: lines.join('\n'),
	details,
	ids: c.items.map(i => i.id),
	email: p.email,
	scripts: c.scripts.map(s => ({ id: s.id, patterns: s.patterns, answer: s.answer })),
}

const file = `// Generated by scripts/export-facts.mjs from src/content.ts. Do not edit by hand: run \`npm run facts\`.
// Files in /api that start with an underscore are not deployed as functions.

export const FACTS = ${JSON.stringify(out, null, '\t')} as const
`
writeFileSync(join(root, 'api', '_facts.ts'), file)
console.log(`api/_facts.ts: ${out.ids.length} items, ${out.knowledge.length} characters of facts`)
