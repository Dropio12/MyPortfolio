export type Glyph = { w: number; h: number; dy: number; runs: number[] }

const compile = (src: string, capH: number): Glyph => {
	const rows = src.split('|')
	const runs: number[] = []
	rows.forEach((row, y) => {
		let x = 0
		while (x < row.length) {
			if (row[x] === '#') {
				let e = x
				while (e < row.length && row[e] === '#') e++
				runs.push(x, y, e - x)
				x = e
			} else x++
		}
	})
	return { w: rows[0].length, h: rows.length, dy: capH - rows.length, runs }
}

const cache: Record<string, Glyph> = {}

export const glyph = (ch: string, small: boolean): Glyph | null => {
	const key = (small ? 's' : 'b') + ch
	if (cache[key]) return cache[key]
	const table = small ? SMALL : BIG
	const src = table[ch] || table[ch.toUpperCase()]
	if (!src) return null
	cache[key] = compile(src, small ? 5 : 7)
	return cache[key]
}

/** Width in pixels of a string set in one of the fonts, with one pixel between glyphs. */
export const textWidth = (s: string, small = false) => {
	let w = 0
	for (const ch of s) {
		const g = glyph(ch, small)
		w += (g ? g.w : 3) + 1
	}
	return Math.max(0, w - 1)
}
